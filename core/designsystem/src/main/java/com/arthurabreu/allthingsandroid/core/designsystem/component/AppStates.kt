private fun AppLoadingPreview() {
    AllThingsAndroidTheme { AppLoadingIndicator() }
}

@Preview(showBackground = true)
@Composable
private fun AppErrorPreview() {
    AllThingsAndroidTheme { AppErrorState(message = "Something went wrong", onRetry = {}) }
}

@Preview(showBackground = true)
@Composable
private fun AppEmptyPreview() {
    AllThingsAndroidTheme { AppEmptyState(message = "No results found") }
}
